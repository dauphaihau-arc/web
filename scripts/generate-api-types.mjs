#!/usr/bin/env node
/**
 * Generates two committed artifacts from the OpenAPI contract, falling back to
 * the sibling API checkout for local development without registry credentials:
 *   - `packages/schemas/src/api/generated/openapi.d.ts` — response/request types
 *   - `packages/schemas/src/api/generated/api-enums.ts` — every string-valued
 *     `enum` tuple, keyed by its location in the document
 *
 * Usage:
 *   node ./scripts/generate-api-types.mjs
 *   node ./scripts/generate-api-types.mjs --check
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import openapiTS from 'openapi-typescript'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT_PATH = resolve(repoRoot, 'packages/schemas/src/api/generated/openapi.d.ts')
const ENUMS_OUTPUT_PATH = resolve(repoRoot, 'packages/schemas/src/api/generated/api-enums.ts')
const PUBLISHED_SPEC = resolve(repoRoot, 'node_modules/@dauphaihau-arc/api-spec/openapi.json')
const LOCAL_SPEC = resolve(repoRoot, '../api/api/openapi.json')
const HEADER =
  '// Generated by scripts/generate-api-types.mjs from @dauphaihau-arc/api-spec. Do not edit.'
const ENUMS_HEADER =
  '// Generated by scripts/generate-api-types.mjs from @dauphaihau-arc/api-spec into api-enums.ts. Do not edit.'

/** Arguments after pnpm's forwarded `--` separator, if any. */
const args = process.argv.slice(2).filter((arg) => arg !== '--')
const checkOnly = args.includes('--check')

function resolveSpec() {
  if (existsSync(PUBLISHED_SPEC)) {
    console.log(`using published package at ${PUBLISHED_SPEC}`)
    return { source: 'published-package', path: PUBLISHED_SPEC }
  }

  if (existsSync(LOCAL_SPEC)) {
    console.log(`using local checkout at ${LOCAL_SPEC}`)
    return { source: 'local-checkout', path: LOCAL_SPEC }
  }

  console.error(
    [
      'Could not resolve the OpenAPI spec.',
      `  expected published package: ${PUBLISHED_SPEC}`,
      `  expected local checkout:    ${LOCAL_SPEC}`,
      'Install @dauphaihau-arc/api-spec (see .npmrc) or check out the api submodule.',
    ].join('\n'),
  )
  process.exit(1)
}

function normaliseNewlines(value) {
  return value.replace(/\r\n?/g, '\n')
}

function splitLines(value) {
  const lines = normaliseNewlines(value).split('\n')
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop()
  return lines
}

function firstDifference(expected, actual) {
  const expectedLines = splitLines(expected)
  const actualLines = splitLines(actual)
  const max = Math.max(expectedLines.length, actualLines.length)

  for (let index = 0; index < max; index += 1) {
    const before = expectedLines[index]
    const after = actualLines[index]
    if (before === after) continue

    let column = 0
    const limit = Math.min(before?.length ?? 0, after?.length ?? 0)
    while (column < limit && before[column] === after[column]) column += 1

    return {
      line: index + 1,
      column: column + 1,
      expected,
      actual,
      before: before ?? '<end of file>',
      after: after ?? '<end of file>',
      addedLines: Math.max(0, actualLines.length - expectedLines.length),
      removedLines: Math.max(0, expectedLines.length - actualLines.length),
    }
  }

  return null
}

/**
 * A tuple's stable key is the location of the schema that owns the `enum`
 * keyword, with OpenAPI plumbing suffixes removed:
 *   paths./v1/me/orders.get.parameters.5.schema          -> ...parameters.5
 *   paths./v1/...shipping-profiles.get.parameters.1.schema.items -> ...parameters.1
 *   components.schemas.X.properties.status               -> unchanged
 */
function enumLocation(location) {
  return location.replace(/\.schema(\.items)?$/, '')
}

function collectStringEnums(node, location = '', tuples = new Map()) {
  if (Array.isArray(node)) {
    node.forEach((value, index) => collectStringEnums(value, `${location}.${index}`, tuples))
    return tuples
  }

  if (!node || typeof node !== 'object') return tuples

  if (Array.isArray(node.enum) && node.enum.every((value) => typeof value === 'string')) {
    const key = enumLocation(location)
    const values = [...node.enum]
    const existing = tuples.get(key)
    if (existing && JSON.stringify(existing) !== JSON.stringify(values)) {
      throw new Error(
        `ambiguous enum location ${key}: ${JSON.stringify(existing)} vs ${JSON.stringify(values)}`,
      )
    }
    tuples.set(key, values)
  }

  for (const [key, value] of Object.entries(node)) {
    collectStringEnums(value, location ? `${location}.${key}` : key, tuples)
  }

  return tuples
}

function renderEnums(tuples) {
  const entries = [...tuples.keys()]
    .sort()
    .map((key) => {
      const values = tuples.get(key).map((value) => JSON.stringify(value)).join(', ')
      return `  ${JSON.stringify(key)}: [${values}]`
    })
    .join(',\n')

  return [
    ENUMS_HEADER,
    '',
    '/**',
    ' * Every string-valued `enum` tuple from the OpenAPI document, keyed by its',
    ' * location in the spec. Numeric and boolean enums are omitted.',
    ' */',
    'export const API_ENUM_VALUES = {',
    entries,
    '} as const',
    '',
  ].join('\n')
}

async function generate() {
  const { path } = resolveSpec()
  const schema = JSON.parse(readFileSync(path, 'utf8'))
  const generated = await openapiTS(schema, { commentHeader: HEADER })
  const artifacts = [
    {
      path: OUTPUT_PATH,
      content: `${normaliseNewlines(generated).replace(/\n*$/, '')}\n`,
    },
    {
      path: ENUMS_OUTPUT_PATH,
      content: normaliseNewlines(renderEnums(collectStringEnums(schema))),
    },
  ]

  if (!checkOnly) {
    for (const artifact of artifacts) {
      mkdirSync(dirname(artifact.path), { recursive: true })
      writeFileSync(artifact.path, artifact.content, 'utf8')
      console.log(`wrote ${artifact.path} (${splitLines(artifact.content).length} lines)`)
    }
    return
  }

  let drifted = false
  for (const artifact of artifacts) {
    if (!existsSync(artifact.path)) {
      console.error(`drift: ${artifact.path} does not exist; run \`pnpm generate:api-types\`.`)
      drifted = true
      continue
    }

    const committed = readFileSync(artifact.path, 'utf8')
    if (committed === artifact.content) {
      console.log(`up to date: ${artifact.path}`)
      continue
    }

    drifted = true
    console.error(`drift: ${artifact.path} is out of date`)
    const diff = firstDifference(committed, artifact.content)
    if (diff) {
      console.error(
        `  first difference at line ${diff.line}, column ${diff.column}\n` +
          `  - ${diff.before}\n` +
          `  + ${diff.after}\n` +
          `  added lines: ${diff.addedLines}, removed lines: ${diff.removedLines}`,
      )
    }
  }

  if (drifted) process.exit(1)
}

generate().catch((error) => {
  console.error(error)
  process.exit(1)
})
